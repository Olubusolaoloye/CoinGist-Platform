// Writes packages/db/dev/sql.generated.ts: the Supabase shim and every migration as strings,
// so serverless bundles (which don't ship files read from disk) can build the demo database.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const migrationsDir = join(root, "supabase/migrations");
const shim = await readFile(join(here, "../dev/supabase-shim.sql"), "utf8");
const names = (await readdir(migrationsDir)).filter((f) => f.endsWith(".sql")).sort();
const migrations = await Promise.all(
  names.map(async (name) => ({ name, sql: await readFile(join(migrationsDir, name), "utf8") })),
);
const out = `// GENERATED by packages/db/scripts/embed-sql.mjs. Do not edit; do not commit.
export const SHIM_SQL: string = ${JSON.stringify(shim)};
export const MIGRATIONS: Array<{ name: string; sql: string }> = ${JSON.stringify(migrations, null, 2)};
`;
await writeFile(join(here, "../dev/sql.generated.ts"), out);
console.log(`embedded shim + ${migrations.length} migrations`);
